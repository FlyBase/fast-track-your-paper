const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const { JSDOM } = require('jsdom')
const root = path.resolve(__dirname, '..')
const base = (process.env.PUBLIC_URL || '/submission/publication').replace(
  /\/$/,
  ''
)
if (!/^\/[a-zA-Z0-9/_-]+$/.test(base))
  throw new Error('PUBLIC_URL must be a local path prefix')
let html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8')
// These are the audited shared header scripts, not the React application.
const retired = [
  'jquery/jquery.min.js',
  'bootstrap3/bootstrap.min.js',
  'simpleStorage/simpleStorage.js',
  'FBsession.js',
  'j2g.js',
  'typeahead/typeahead.jquery.js',
  'flybase_autocomplete.js',
  'jquery/jquery.cookie.js',
]
const retained = new Set(['google_analytics.js', 'autotrack/autotrack.js', 'recovery-maintenance.js'])
const dom = new JSDOM(html)
const doc = dom.window.document
const seen = new Map([...retired, ...retained].map((name) => [name, 0]))
let analytics = 0
for (const script of doc.querySelectorAll('script')) {
  const src = script.getAttribute('src')
  if (src === null) {
    if (/\b(?:jQuery|simpleStorage|getFBsession|FBsession|activate_autocomplete)\b|(?:^|[^\w$])\$\s*[.(]/.test(script.textContent))
      throw new Error('Inline script references a removed header dependency')
    continue
  }
  if (src === 'https://www.google-analytics.com/analytics.js') {
    analytics += 1
    continue
  }
  // Validate DOM attributes, not HTML quote style. Absolute/protocol-relative
  // shared URLs and every new script require a reviewed contract update.
  const match = /^\/js\/([^?#]+)(?:\?[^#]*)?$/.exec(src)
  const name = match && match[1]
  if (!seen.has(name)) throw new Error(`Unaudited shared script: ${src}`)
  seen.set(name, seen.get(name) + 1)
  if (!retained.has(name)) script.remove()
}
for (const [name, count] of seen) {
  if (count !== 1) throw new Error(`Expected one legacy script ${name}; found ${count}`)
}
if (analytics !== 1) throw new Error('Expected one retained analytics loader')
// Transform generated markup only. The reviewed source fragments, analytics,
// maintenance script and native hamburger/resize handler remain unchanged.
for (const id of ['header2023', 'stack-nav', 'j2g_search_form', 'GeneSearch', 'GeneSearchSlct']) {
  if (doc.querySelectorAll('#' + id).length !== 1)
    throw new Error('Expected one production header element: ' + id)
}
for (const navbar of doc.querySelectorAll('#header2023, #stack-nav')) {
  for (const el of navbar.querySelectorAll('[data-toggle], [data-target], [data-slide], [data-slide-to], [data-wrap]')) {
    for (const name of ['toggle', 'target', 'slide', 'slide-to', 'wrap']) {
      if (!el.hasAttribute('data-' + name)) continue
      if (name === 'toggle' && el.getAttribute('data-toggle') !== 'dropdown')
        throw new Error('Unaudited production header toggle')
      el.setAttribute('data-bs-' + name, el.getAttribute('data-' + name))
      el.removeAttribute('data-' + name)
    }
  }
  navbar.querySelectorAll('.carousel-inner > .item').forEach(el => el.classList.add('carousel-item'))
}
html = dom.serialize()
dom.window.close()
const bootstrap = require('bootstrap/package.json')
if (!/^5\.3\.\d+$/.test(bootstrap.version))
  throw new Error('Expected tested Bootstrap 5.3.x')
const assets = path.join(root, 'public/ftyp-header')
fs.mkdirSync(assets, { recursive: true })
// This namespace is generated by this script. Remove only prior generated hash
// files, so rebuilding does not publish obsolete executable copies.
for (const filename of fs.readdirSync(assets)) {
  if (
    /^(?:bootstrap-5\.3\.\d+|ftyp-header)-[a-f0-9]{16}\.(?:js|css)$/.test(
      filename
    )
  ) {
    fs.unlinkSync(path.join(assets, filename))
  }
}
function publish(source, name, extension) {
  const bytes = fs.readFileSync(source)
  const digest = crypto
    .createHash('sha256')
    .update(bytes)
    .digest('hex')
    .slice(0, 16)
  const filename = `${name}-${digest}.${extension}`
  fs.writeFileSync(path.join(assets, filename), bytes)
  return `${base}/ftyp-header/${filename}`
}
const bs = publish(
  require.resolve('bootstrap/dist/js/bootstrap.bundle.min.js'),
  `bootstrap-${bootstrap.version}`,
  'js'
)
const js = publish(
  path.join(root, 'header/ftyp-header.js'),
  'ftyp-header',
  'js'
)
const css = publish(
  path.join(root, 'header/ftyp-header.css'),
  'ftyp-header',
  'css'
)
fs.copyFileSync(
  require.resolve('bootstrap/LICENSE'),
  path.join(assets, 'bootstrap-LICENSE.txt')
)
fs.copyFileSync(
  require.resolve('@popperjs/core/LICENSE.md'),
  path.join(assets, 'popper-LICENSE.md')
)
html = html
  .replace('</head>', `  <link rel="stylesheet" href="${css}">\n</head>`)
  .replace(
    '</body>',
    `  <script src="${bs}"></script>\n  <script src="${js}"></script>\n  <script type="module" src="/src/index.js"></script>\n</body>`
  )
fs.writeFileSync(
  path.join(root, 'index.html'),
  html.replace(/%PUBLIC_URL%/g, base)
)
