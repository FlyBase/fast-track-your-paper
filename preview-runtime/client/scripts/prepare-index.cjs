const fs = require('node:fs')
const path = require('node:path')
const crypto = require('node:crypto')
const root = path.resolve(__dirname, '..')
const base = (process.env.PUBLIC_URL || '/submission/publication').replace(
  /\/$/,
  ''
)
if (!/^\/[a-zA-Z0-9/_-]+$/.test(base))
  throw new Error('PUBLIC_URL must be a local path prefix')
let html = fs.readFileSync(path.join(root, 'public/index.html'), 'utf8')
// These are the audited shared header scripts, not the React application.
const retired = [
  'google_analytics.js',
  'autotrack/autotrack.js',
  'jquery/jquery.min.js',
  'bootstrap3/bootstrap.min.js',
  'simpleStorage/simpleStorage.js',
  'FBsession.js',
  'j2g.js',
  'typeahead/typeahead.jquery.js',
  'flybase_autocomplete.js',
  'jquery/jquery.cookie.js',
]
const seen = new Map(retired.map((name) => [name, 0]))
html = html.replace(
  /<script\b[^>]*\bsrc="\/js\/([^"?]+)(?:\?[^"<>]*)?"[^>]*>\s*<\/script>/g,
  (tag, name) => {
    if (!seen.has(name)) throw new Error(`Unaudited shared script: ${name}`)
    seen.set(name, seen.get(name) + 1)
    return ''
  }
)
for (const [name, count] of seen) {
  if (count !== 1)
    throw new Error(`Expected one legacy script ${name}; found ${count}`)
}
// Limit markup migration to the single header nav, not application templates.
let navs = 0
html = html.replace(/<nav\b[^>]*>[\s\S]*?<\/nav>/g, (nav) => {
  if (!nav.includes('id="j2g_search_form"')) return nav
  navs += 1
  return nav
    .replace('<nav ', '<nav id="flybase-preview-navbar" ')
    .replace(/data-toggle="(dropdown|collapse)"/g, 'data-bs-toggle="$1"')
    .replace(/data-target=/g, 'data-bs-target=')
})
if (navs !== 1) throw new Error('Expected one standalone preview header nav')
if (
  (html.match(/<\/head>/g) || []).length !== 1 ||
  (html.match(/<\/body>/g) || []).length !== 1
)
  throw new Error('Expected one HTML head and body')
const bootstrap = require('bootstrap/package.json')
if (!/^5\.3\.\d+$/.test(bootstrap.version))
  throw new Error('Expected tested Bootstrap 5.3.x')
const assets = path.join(root, 'public/ftyp-header')
fs.mkdirSync(assets, { recursive: true })
// This namespace is generated by this script. Remove only prior generated hash
// files, so rebuilding does not publish obsolete executable copies.
for (const filename of fs.readdirSync(assets)) {
  if (
    /^(?:bootstrap-5\.3\.\d+|preview-header)-[a-f0-9]{16}\.(?:js|css)$/.test(
      filename
    )
  ) {
    fs.unlinkSync(path.join(assets, filename))
  }
}
function publish(source, name, extension) {
  const bytes = fs.readFileSync(source)
  const digest = crypto
    .createHash('sha256')
    .update(bytes)
    .digest('hex')
    .slice(0, 16)
  const filename = `${name}-${digest}.${extension}`
  fs.writeFileSync(path.join(assets, filename), bytes)
  return `${base}/ftyp-header/${filename}`
}
const bs = publish(
  require.resolve('bootstrap/dist/js/bootstrap.bundle.min.js'),
  `bootstrap-${bootstrap.version}`,
  'js'
)
const js = publish(
  path.join(root, 'header/preview-header.js'),
  'preview-header',
  'js'
)
const css = publish(
  path.join(root, 'header/preview-header.css'),
  'preview-header',
  'css'
)
fs.copyFileSync(
  require.resolve('bootstrap/LICENSE'),
  path.join(assets, 'bootstrap-LICENSE.txt')
)
fs.copyFileSync(
  require.resolve('@popperjs/core/LICENSE.md'),
  path.join(assets, 'popper-LICENSE.md')
)
html = html
  .replace('</head>', `  <link rel="stylesheet" href="${css}">\n</head>`)
  .replace(
    '</body>',
    `  <script src="${bs}"></script>\n  <script src="${js}"></script>\n  <script type="module" src="/src/index.js"></script>\n</body>`
  )
fs.writeFileSync(
  path.join(root, 'index.html'),
  html.replace(/%PUBLIC_URL%/g, base)
)
